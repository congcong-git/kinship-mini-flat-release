/**
 * 辞书称谓对照库
 * ================
 *
 * 中文亲属称谓有两套命名系统，但它们说的是**同一个亲属位置**，
 * 只是用词不同，不改变关系的归属：
 *
 *   1. 口语系统：直接给一个词        （表伯父 / 堂舅）
 *   2. 辞书系统：《尔雅》的「X之Y」结构（从父晜弟 / 从舅）
 *
 * 辞书依据（《尔雅·释亲·母党》）
 * ------------------------------
 *   「母之考，为外王父；母之妣，为外王母。」
 *   「母之王考，为外曾王父；母之王妣，为外曾王母。」
 *   「母之晜弟，为舅；母之从父晜弟，为从舅。」  ← MB = 舅，MFBS = 从舅
 *   「母之姊妹，为从母。」                      ← MR = 从母（姨）
 *   「从母之男子，为从母晜弟；其女子子，为从母姊妹。」
 *   「谓我舅者，吾谓之甥也。」
 *
 * 《尔雅·释亲·宗族》
 *   「父之从父晜弟，为从祖父。」                ← FFBS = 从祖父
 *   「父之从祖晜弟，为族父。」
 *   「兄之子、弟之子，相谓为从父晜弟。」
 *
 * ⚠ 曾经把 MFBS（外祖父兄弟的儿子）当成「表伯父」，理由是「换个锚点就是
 *   另一个名字：以我为锚点叫表伯父，以母为锚点叫堂舅，两个都对」。
 *   这是错的。母亲叫他「堂兄」，不是「表兄」——「堂」来自母亲与他同宗
 *   （共曾祖父、同姓），整条链上没有任何「表」的成分，两个锚点都落在「堂」。
 *
 *   辞书也直接给了答案：《尔雅》把 MFBS 写作「从舅」，归入母党「舅」类；
 *   父党的表亲在「宗族」篇，两章不相干。今称「堂舅」。
 *
 *   另外「伯」的基准只能是父亲。MFBS 与父亲之间没有任何路径关系，
 *   所以「表伯父」里的「伯」字无从产生。
 */

