/** 取某个键的词条，找不到返回 null */
function get(key) {
  var parts = key.split('.');
  var cur = CLASSICAL;
  for (var i = 0; i < parts.length; i++) {
    if (!cur || typeof cur !== 'object') return null;
    cur = cur[parts[i]];
  }
  return cur || null;
}

